def graphics():
    # 0 км пробега
    a = w('ни', 10.4); b = w('они', 12.1)
    an = R.POP + "\\org(540,1255)"
    R.S(1, a, b, f"\\1c&H101010&\\1a&H50&\\3c{GOLD}\\bord4{an}", box(230, 1140, 850, 1370))
    R.D(2, a, b, 'Small', f"{{\\pos(540,1202){an}}}ПРОБЕГ")
    R.D(2, a, b, 'Big', f"{{\\pos(540,1295)\\c{GOLD}{an}}}0 КМ")
    # комплекс МАКСИМАЛЬНЫЙ
    R.plate(w('комплекс', 14.1) + 0.05, w('бампер', 19.3) - 0.05, 'КОМПЛЕКС', 'МАКСИМАЛЬНЫЙ')
    # чек-лист, галочка на произнесении
    items = [('БАМПЕР', w('бампер', 19.3)), ('ОПТИКА', w('оптика', 20.8)), ('КАПОТ', w('капот', 21.7)),
             ('КРЫЛЬЯ', w('крылья', 22.9)), ('СТОЙКИ', w('стойки', 24.9)), ('ПОЛОСА НА КРЫШУ', w('полоса', 25.9)),
             ('КАНТЫ ДВЕРЕЙ', w('кантики', 28.8)), ('КАНТ БАГАЖНИКА', w('кант', 29.9)),
             ('ЗОНА ПОГРУЗКИ', w('погрузочная', 31.3)), ('ВНУТР. ПОРОГИ', w('внутренние', 32.4))]
    R.checklist(w('бампер', 19.3) - 0.1, R.src_end(C, 33.44) + 0.6, items)
    # антиманикюр -> ручки
    a = w('отсутствуют', 36.8); b = R.src_end(C, 43.5) + 0.5; t2 = w('ручки', 40.5)
    R.S(1, a, b, f"\\1c{DARK}\\1a&H48&\\3c{GOLD}\\bord3\\fad(200,250)", box(130, 1140, 950, 1400))
    R.S(2, a, b, "\\1c&H5050E0&\\fad(150,250)", cross(205, 1210, 24))
    R.D(2, a, b, 'Item', f"{{\\an4\\pos(255,1210)\\c&HB0B0B0&\\fad(150,250)\\fscx130\\fscy130}}АНТИМАНИКЮР")
    R.S(2, a, b, "\\1c&H909090&\\fad(150,250)", rect(250, 1207, 600, 1213))
    R.S(2, t2, b, f"\\1c{GOLD}\\fad(150,250)", circle(205, 1320, 26))
    R.S(3, t2, b, "\\1c&H101010&\\fad(150,250)", check(188, 1304, 0.95))
    R.D(2, t2, b, 'Item', f"{{\\an4\\pos(255,1320)\\fad(150,250)\\fscx130\\fscy130}}РУЧКИ {{\\c{GOLD}}}ЦЕЛИКОМ")
    # бампер без разбора
    R.plate(w('без', 80.3), w('сэкономит', 81.2) - 0.03, 'БАМПЕР', 'БЕЗ РАЗБОРА')
    # календарь −1–2 дня
    a = w('сэкономит', 81.2); b = R.src_end(C, 83.3) + 0.45
    R.S(1, a, b, f"\\1c{DARK}\\1a&H48&\\3c{GOLD}\\bord3\\fad(150,0)", box(120, 1140, 960, 1420))
    R.S(2, a, b, f"\\1a&HFF&\\3c{GOLD}\\bord5\\fad(150,0)", box(190, 1200, 370, 1370, 16))
    R.S(2, a, b, f"\\1c{GOLD}\\fad(150,0)", rect(190, 1200, 370, 1245))
    for x in (235, 325):
        R.S(3, a, b, f"\\1c{GOLD}\\fad(150,0)", box(x - 7, 1182, x + 7, 1218, 6))
    R.S(3, a, b, "\\1c&HFFFFFF&\\fad(150,0)", cross(280, 1308, 30, 8))
    R.D(2, a, b, 'Big', f"{{\\an4\\pos(420,1245)\\c{GOLD}\\fad(150,0)\\fscx80\\fscy80\\t(0,200,\\fscx100\\fscy100)}}−1–2")
    R.D(2, a, b, 'Days', f"{{\\an4\\pos(420,1335)\\fad(200,0)\\fscx72\\fscy72}}РАБОЧИХ ДНЯ")
    # забрать завтра
    R.plate(w('забрать', 101.0), w('а', 102.7) - 0.03, 'МАШИНА ГОТОВА', 'ЗАВТРА')
    R.endcard()
    t0, t1 = w('бампер', 19.3) - 0.1, R.src_end(C, 33.44) + 0.6
    return lambda t: 990 if t0 <= t < t1 else 1050


def sfx():
    items = [('бампер', 19.3), ('оптика', 20.8), ('капот', 21.7), ('крылья', 22.9), ('стойки', 24.9),
             ('полоса', 25.9), ('кантики', 28.8), ('кант', 29.9), ('погрузочная', 31.3), ('внутренние', 32.4)]
    s = [('hit3', w('ни', 10.4), -21), ('hit5', w('комплекс', 14.1) + 0.05, -20)]
    s += [('hit4', w(t, a), -26) for t, a in items]
    s += [('hit1', w('отсутствуют', 36.8), -22), ('hit4', w('ручки', 40.5), -23),
          ('hit3', w('без', 80.3), -21), ('hit1', w('сэкономит', 81.2), -23),
          ('hit5', w('забрать', 101.0), -20), ('hit5', R.VOICE_END + 0.1, -18)]
    return s


