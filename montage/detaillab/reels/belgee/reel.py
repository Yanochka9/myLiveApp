def graphics():
    F = R.FLASH
    # хук: 350 BYN · 3,5 ЧАСА
    for (x1, x2, txt, t0) in [(150, 520, '350 BYN', h('350')), (560, 930, '3,5 ЧАСА', h('часа'))]:
        an = R.POP + f"\\org({(x1+x2)//2},1245)"
        R.S(1, t0, F - 0.05, f"\\1c&H101010&\\1a&H40&\\3c{GOLD}\\bord4{an}", box(x1, 1175, x2, 1315, 30))
        R.D(2, t0, F - 0.05, 'Chip', f"{{\\pos({(x1+x2)//2},1247)\\c{GOLD}{an}}}{txt}")
    # схема авто: задняя полусфера
    a = w('тонировку', 4.2); b = w('приехал', 8.0) - 0.05
    fa = "\\fad(220,220)"
    R.S(1, a, b, f"\\1c{DARK}\\1a&H40&\\3c{GOLD}\\bord3{fa}", box(150, 1120, 930, 1480))
    R.D(2, a, b, 'Small', f"{{\\pos(540,1168)\\c{GOLD}{fa}}}ЗАДНЯЯ ПОЛУСФЕРА")
    R.S(2, a, b, f"\\1c&H2E2E2E&\\3c&H909090&\\bord3{fa}", box(250, 1215, 830, 1435, 80))
    R.S(3, a, b, f"\\1c&H1A1A1A&{fa}", rect(390, 1238, 660, 1412))
    R.S(3, a, b, f"\\1c&H8A8A8A&{fa}", "m 660 1238 l 745 1258 l 745 1392 l 660 1412")
    R.S(3, a, b, f"\\1c&H8A8A8A&{fa}", rect(530, 1222, 650, 1233) + ' ' + rect(530, 1417, 650, 1428))
    glow = f"\\1c{GOLD}\\fad(300,220)\\t(300,700,\\1c{GOLD2})\\t(700,1100,\\1c{GOLD})"
    t1 = a + 0.35
    R.S(4, t1, b, glow, "m 318 1252 l 390 1238 l 390 1412 l 318 1398")
    R.S(4, t1, b, glow, rect(400, 1222, 520, 1233) + ' ' + rect(400, 1417, 520, 1428))
    R.D(4, t1, b, 'Tiny', f"{{\\pos(355,1325)\\c&H101010&\\fad(300,220)}}5%")
    # комплекс БАЗОВЫЙ+
    R.plate(w('базовый', 11.6) - 0.05, w('передней', 13.8) - 0.05, 'КОМПЛЕКС', 'БАЗОВЫЙ+')
    # чек-лист
    items = [('ОПТИКА', w('передней', 13.8)), ('КАПОТ', w('капота', 15.4)), ('КРЫЛЬЯ', w('крыльев', 16.5)),
             ('СТОЙКИ', w('стойки', 18.1)), ('ПОЛОСА НА КРЫШУ', w('полосы', 19.1)),
             ('АНТИМАНИКЮР', w('антиманикюры', 20.4)), ('КАНТЫ ДВЕРЕЙ', w('канты', 21.3)),
             ('ВНУТР. ПОРОЖКИ', w('внутренние', 22.3)), ('ЗОНА ПОГРУЗКИ', w('погрузочная', 23.8)),
             ('КАНТ БАГАЖНИКА', w('кант', 24.7))]
    l0, l1 = w('передней', 13.8) - 0.1, R.src_end('3427', 25.94) + 0.6
    R.checklist(l0, l1, items)
    # плёнка Quantum 5%
    a = w('пленку', 30.7); b = R.src_end('3427', 33.94) + 0.5
    R.S(1, a, b, f"\\1c{DARK}\\1a&H40&\\3c{GOLD}\\bord3\\fad(200,250)", box(120, 1130, 960, 1440))
    R.D(2, a, b, 'Small', f"{{\\pos(540,1182)\\c{GOLD}\\fad(200,250)}}ПЛЁНКА QUANTUM")
    t5 = w('5', 31.9)
    R.D(2, t5, b, 'Big', f"{{\\an6\\pos(440,1285)\\c{GOLD}\\fad(150,250)\\fscx80\\fscy80\\t(0,200,\\fscx100\\fscy100)}}5%")
    R.D(2, t5, b, 'Item', f"{{\\an4\\pos(475,1285)\\fad(200,250)\\fscx120\\fscy120}}СВЕТОПРОПУСКАНИЕ")
    R.S(2, t5, b, "\\1c&H505050&\\fad(200,250)", box(180, 1370, 900, 1392, 11))
    R.S(3, t5 + 0.2, b, f"\\1c{GOLD}\\fad(200,250)", box(180, 1370, 216, 1392, 11))
    # защита от УФ
    a = v('ультрафиолетовых', 27.8) - 0.1; b = v('также', 31.4) - 0.05
    R.S(1, a, b, f"\\1c{DARK}\\1a&H40&\\3c{GOLD}\\bord3\\fad(200,250)", box(130, 1140, 950, 1400))
    cx, cy = 255, 1270
    R.S(2, a, b, f"\\1c{GOLD}\\fad(200,250)", circle(cx, cy, 38))
    rays = []
    for k in range(8):
        ang = k * math.pi / 4; c_, s_ = math.cos(ang), math.sin(ang)
        p = [(52, -6), (80, -6), (80, 6), (52, 6)]
        pts = [(cx + x * c_ - y * s_, cy + x * s_ + y * c_) for x, y in p]
        rays.append("m " + " l ".join(f"{x:.0f} {y:.0f}" for x, y in pts))
    R.S(2, a, b, f"\\1c{GOLD}\\fad(200,250)\\frz0", ' '.join(rays))
    R.S(3, a + 0.25, b, "\\1c&H5050E0&\\fad(150,250)", cross(cx, cy, 56, 9))
    R.D(2, a, b, 'Item', f"{{\\an4\\pos(370,1225)\\fad(200,250)\\fscx130\\fscy130}}ЗАЩИТА САЛОНА")
    R.D(2, a, b, 'Days', f"{{\\an4\\pos(370,1315)\\c{GOLD}\\fad(200,250)\\fscx80\\fscy80}}ОТ УФ-ЛУЧЕЙ")
    # порожки шире и ниже
    a = v('шире', 34.6) - 0.1; b = v('песочек', 38.9) + 0.9
    R.S(1, a, b, f"\\1c{DARK}\\1a&H40&\\3c{GOLD}\\bord3\\fad(200,250)", box(130, 1130, 950, 1440))
    R.D(2, a, b, 'Small', f"{{\\pos(540,1182)\\c{GOLD}\\fad(200,250)}}ВНУТРЕННИЕ ПОРОЖКИ")
    R.S(2, a, b, f"\\1c{GOLD}\\fad(200,250)",
        "m 190 1290 l 235 1262 l 235 1279 l 445 1279 l 445 1262 l 490 1290 l 445 1318 l 445 1301 l 235 1301 l 235 1318")
    R.D(2, a, b, 'Step', f"{{\\pos(340,1375)\\fad(200,250)}}ШИРЕ")
    tn = v('вниз', 36.1) - 0.1
    R.S(2, tn, b, f"\\1c{GOLD}\\fad(200,250)", "m 700 1235 l 740 1235 l 740 1300 l 770 1300 l 720 1350 l 670 1300 l 700 1300")
    R.D(2, tn, b, 'Step', f"{{\\pos(720,1395)\\fad(200,250)}}НИЖЕ")
    R.endcard()
    return lambda t: 990 if l0 <= t < l1 else 1050


