def sxp(path, k=0.9):
    """сжать рисунок по ширине к центру кадра (безопасная зона Reels)"""
    t = path.split(); out = []; i = 0
    while i < len(t):
        if t[i] in 'mlb':
            out.append(t[i]); i += 1; continue
        out += [f"{540 + (float(t[i]) - 540) * k:.0f}", t[i + 1]]; i += 2
    return ' '.join(out)


def d3(t0, t1, x, y, txt, delay=0):
    """объёмная надпись: экструзия + переворот с наездом + блик"""
    fly = (f"\\org({x},{y})\\frx75\\fscx60\\fscy60\\t({delay},{delay+260},\\frx-8\\fscx112\\fscy112)"
           f"\\t({delay+260},{delay+420},\\frx0\\fscx100\\fscy100)\\fad({delay+120},200)")
    for k in range(10, 0, -1):
        col = f"&H{0x10 + k:02X}{0x3C + k*3:02X}{0x5A + k*4:02X}&"
        R.D(6, t0, t1, 'D3', f"{{\\pos({x+k*1.6:.1f},{y+k*2.2:.1f})\\c{col}{fly}}}{txt}")
    R.D(7, t0, t1, 'D3', f"{{\\pos({x},{y})\\c{GOLD}\\bord0{fly}}}{txt}")
    R.D(8, t0, t1, 'D3', f"{{\\pos({x},{y})\\c&HFFFFFF&\\alpha&H40&{fly}"
                         f"\\clip({x-420},0,{x-380},1920)\\t({delay+450},{delay+900},\\clip({x+380},0,{x+420},1920))}}{txt}")


STAR = "m 0 -34 l 7 -7 l 34 0 l 7 7 l 0 34 l -7 7 l -34 0 l -7 -7"


def num3d(t0, t1, x, y, txt, layers=7, tags=''):
    """объёмная цифра без анимации (экструзия вниз-вправо + золотой фронт)"""
    for k in range(layers, 0, -1):
        col = f"&H{0x10 + k:02X}{0x3C + k*3:02X}{0x5A + k*4:02X}&"
        R.D(6, t0, t1, 'D3', f"{{\\pos({x+k*1.5:.1f},{y+k*2.0:.1f})\\c{col}{tags}}}{txt}")
    R.D(7, t0, t1, 'D3', f"{{\\pos({x},{y})\\c{GOLD}{tags}}}{txt}")


def counter(t0, t1, dur, x, y, final, fmt, layers=7):
    """число набегает от нуля к final (ease-out), потом стоит объёмным с лёгким «пульсом»"""
    n = max(2, round(dur * 30))
    for i in range(n):
        e = 1 - (1 - (i + 1) / n) ** 3
        a = t0 + i / 30; b = t0 + (i + 1) / 30
        num3d(a, b, x, y, fmt(final * e), layers)
    num3d(t0 + n / 30, t1, x, y, fmt(final), layers,
          "\\fscx100\\fscy100\\t(0,90,\\fscx112\\fscy112)\\t(90,240,\\fscx100\\fscy100)\\fad(0,150)")


def hook_card(tp, tt, th, ts, t1):
    """хук: стеклянная карточка «350 BYN | 3,5 ЧАСА» — счётчики, ценник, часы со стрелками, блик и блёстки"""
