    # блик по карточке
    R.S(2, tp + 0.35, t1, f"\\1c&HFFFFFF&\\1a&HC8&\\fad(0,150)\\clip(130,0,170,1920)\\t(0,650,\\clip(910,0,950,1920))",
        box(190, y1, 890, y2, 34))
    # золотой разделитель растёт сверху вниз
    R.S(2, tp + 0.25, t1, f"\\1c{GOLD}\\fad(0,150)\\clip(0,{y1+40},1080,{y1+40})\\t(0,350,\\clip(0,{y1+40},1080,{y2-40}))",
        rect(538, y1 + 40, 542, y2 - 40))
    # левая половина: ценник + 350 + BYN
    tag = f"m {xl-38} {y1+40} l {xl+18} {y1+40} l {xl+44} {y1+66} l {xl+18} {y1+92} l {xl-38} {y1+92}"
    R.S(3, tp, t1, f"\\1c{GOLD}{pop}", tag)
    R.S(4, tp, t1, f"\\1c&H101010&{pop}", circle(xl + 16, y1 + 66, 7))
    counter(tp + 0.05, t1, 0.45, xl, yn, 350, lambda v: f"{int(round(v))}")
